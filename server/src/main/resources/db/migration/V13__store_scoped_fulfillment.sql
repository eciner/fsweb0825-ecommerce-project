-- Legacy product.store_id is not a verified relationship. Never infer ownership.
ALTER TABLE product ADD COLUMN fulfillment_store_id BIGINT REFERENCES store(id);
ALTER TABLE order_item ADD COLUMN fulfillment_store_id BIGINT REFERENCES store(id);
CREATE INDEX idx_product_fulfillment_store ON product(fulfillment_store_id);

CREATE TABLE product_fulfillment_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES product(id),
    previous_store_id BIGINT REFERENCES store(id),
    store_id BIGINT REFERENCES store(id),
    actor_id BIGINT NOT NULL REFERENCES app_user(id),
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE shipment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES customer_order(id),
    store_id BIGINT REFERENCES store(id),
    status VARCHAR(20) NOT NULL CHECK (status IN ('ORDER_PLACED','PREPARING','SHIPPED','DELIVERED')),
    version BIGINT NOT NULL DEFAULT 0,
    carrier VARCHAR(100),
    tracking_number VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    historical BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_shipment_order ON shipment(order_id);
CREATE INDEX idx_shipment_store ON shipment(store_id, id);
CREATE INDEX idx_shipment_status ON shipment(status, id);
CREATE TABLE shipment_item (
    shipment_id BIGINT NOT NULL REFERENCES shipment(id),
    order_item_id BIGINT NOT NULL UNIQUE REFERENCES order_item(id),
    PRIMARY KEY (shipment_id, order_item_id)
);
CREATE TABLE shipment_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT NOT NULL REFERENCES shipment(id),
    request_id UUID,
    status VARCHAR(20) NOT NULL,
    carrier VARCHAR(100),
    tracking_number VARCHAR(100),
    actor_id BIGINT REFERENCES app_user(id),
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    kind VARCHAR(30) NOT NULL,
    CONSTRAINT uq_shipment_request UNIQUE (shipment_id, request_id)
);
CREATE INDEX idx_shipment_event_parent ON shipment_event(shipment_id, id);

-- Old orders have no verified purchase-time ownership. Admin manages each as one
-- unassigned group. These timestamps record import, not invented shipping dates.
INSERT INTO shipment(order_id,status,version,created_at,updated_at,historical)
SELECT id,'ORDER_PLACED',0,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP,TRUE FROM customer_order;
INSERT INTO shipment_item(shipment_id,order_item_id)
SELECT s.id,i.id FROM shipment s JOIN order_item i ON i.order_id=s.order_id;
INSERT INTO shipment_event(shipment_id,status,recorded_at,kind)
SELECT id,'ORDER_PLACED',created_at,'HISTORICAL_IMPORT' FROM shipment;
